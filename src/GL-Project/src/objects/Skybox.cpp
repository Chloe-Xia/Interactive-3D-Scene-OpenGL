void Skybox::render(Shader& shader, const glm::mat4& view, const glm::mat4& projection) {
    // 移除视图矩阵的平移部分
    glm::mat4 viewWithoutTranslation = glm::mat4(glm::mat3(view));
    
    shader.use();
    shader.setMat4("view", viewWithoutTranslation);
    shader.setMat4("projection", projection);
    
    // 设置时间混合因子
    float blendFactor = (sin(timeOfDay * 2.0f * glm::pi<float>()) + 1.0f) * 0.5f;
    shader.setFloat("blendFactor", blendFactor);
    
    // 绑定两个天空盒纹理到更高的纹理单元
    glActiveTexture(GL_TEXTURE2);  // 使用纹理单元2
    glBindTexture(GL_TEXTURE_CUBE_MAP, dayCubemapTexture);
    shader.setInt("daySkybox", 2);
    
    glActiveTexture(GL_TEXTURE3);  // 使用纹理单元3
    glBindTexture(GL_TEXTURE_CUBE_MAP, nightCubemapTexture);
    shader.setInt("nightSkybox", 3);
    
    glBindVertexArray(skyboxVAO);
    glDrawArrays(GL_TRIANGLES, 0, 36);
    glBindVertexArray(0);
    
    // 解绑纹理
    glActiveTexture(GL_TEXTURE2);
    glBindTexture(GL_TEXTURE_CUBE_MAP, 0);
    glActiveTexture(GL_TEXTURE3);
    glBindTexture(GL_TEXTURE_CUBE_MAP, 0);
}